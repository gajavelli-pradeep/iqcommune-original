/**
 * Turns the legal markdown into a TypeScript module the app imports.
 *
 * The client sends .docx; docs/legal/*.md is the readable conversion and stays
 * the thing a human edits. This generates content/legal.ts from it.
 *
 * Why generate rather than read the markdown at runtime: Next traces imports to
 * decide what ships in a serverless function, and it cannot see an fs.readFile
 * path. The files live under docs/, which is not traced at all — so a runtime
 * read works on localhost and throws ENOENT in production. An import cannot
 * fail that way.
 *
 *   node scripts/build-legal-content.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

const DOCUMENTS = [
  { key: "privacy", file: "docs/legal/privacy-policy.md", title: "Privacy Policy" },
  { key: "terms", file: "docs/legal/terms-of-use.md", title: "Terms of Use" },
];

/**
 * Enough markdown for these two documents and no more: headings, bullets and
 * paragraphs. A general parser would be more code than the thing it parses, and
 * every input is a file in this repo rather than anything a user supplies.
 */
function parse(markdown) {
  const blocks = [];
  let list = null;

  const flush = () => {
    if (list) {
      blocks.push({ type: "list", items: list });
      list = null;
    }
  };

  for (const raw of markdown.replace(/<!--[\s\S]*?-->/g, "").split("\n")) {
    const line = raw.trim();
    if (!line) {
      flush();
      continue;
    }
    const heading = line.match(/^(#{1,4})\s+(.*)$/);
    if (heading) {
      flush();
      // The document's own h1 is the dialog's title, so it is not repeated in
      // the body; everything below it lifts one level.
      const level = heading[1].length;
      if (level > 1) blocks.push({ type: "heading", level: level - 1, text: heading[2] });
      continue;
    }
    if (line.startsWith("- ")) {
      (list ??= []).push(line.slice(2));
      continue;
    }
    flush();
    blocks.push({ type: "paragraph", text: line });
  }
  flush();
  return blocks;
}

const documents = DOCUMENTS.map(({ key, file, title }) => ({
  key,
  title,
  blocks: parse(readFileSync(path.join(root, file), "utf8")),
}));

const body = `// GENERATED by scripts/build-legal-content.mjs — do not edit.
//
// Source: ${DOCUMENTS.map((d) => d.file).join(", ")}, converted from the client's
// .docx originals. Change the wording there and re-run the script.

export type LegalBlock =
  | { type: "heading"; level: number; text: string }
  | { type: "paragraph"; text: string }
  | { type: "list"; items: string[] };

export interface LegalDocument {
  key: "privacy" | "terms";
  title: string;
  blocks: LegalBlock[];
}

export const LEGAL_DOCUMENTS: readonly LegalDocument[] = ${JSON.stringify(documents, null, 2)} as const;
`;

writeFileSync(path.join(root, "content/legal.ts"), body);
for (const d of documents) {
  const counts = d.blocks.reduce((acc, b) => ({ ...acc, [b.type]: (acc[b.type] ?? 0) + 1 }), {});
  console.log(`${d.key}: ${d.blocks.length} blocks`, counts);
}
